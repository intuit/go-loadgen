package metrics

import (
	"github.com/prometheus/client_golang/prometheus"
)

const (
	totalBytesProcessedName = "total_bytes_processed"
	totalBytesProcessedHelp = "Total bytes processed"
	eventsProcessedName     = "total_events_processed"
	eventsProcessedHelp     = "Total log events generated by the tool."
)

// GetTotalBytesProcessedCounter returns a prom counter for total_bytes_processed metric
func GetTotalBytesProcessedCounter() (promTotalBytesProcessedCounter prometheus.Counter) {
	promTotalBytesProcessedCounter = prometheus.NewCounter(
		prometheus.CounterOpts{
			Name: totalBytesProcessedName,
			Help: totalBytesProcessedHelp,
		},
	)
	return
}

func GetEventsProcessedCounter() (promCounter prometheus.Counter) {
	promCounter = prometheus.NewCounter(
		prometheus.CounterOpts{
			Name: eventsProcessedName,
			Help: eventsProcessedHelp,
		},
	)
	return
}

// NewTotalBytesProcessedCounterFunc returns a total_bytes_processed counter that reads its
// value from total, so that generator threads do not have to update a shared counter.
func NewTotalBytesProcessedCounterFunc(total func() float64) prometheus.CounterFunc {
	return prometheus.NewCounterFunc(prometheus.CounterOpts{
		Name: totalBytesProcessedName,
		Help: totalBytesProcessedHelp,
	}, total)
}

// NewEventsProcessedCounterFunc returns a total_events_processed counter that reads its
// value from total.
func NewEventsProcessedCounterFunc(total func() float64) prometheus.CounterFunc {
	return prometheus.NewCounterFunc(prometheus.CounterOpts{
		Name: eventsProcessedName,
		Help: eventsProcessedHelp,
	}, total)
}
